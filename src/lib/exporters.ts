import { Card, SourceDoc } from '../types'

const TYPE_EMOJI: Record<string, string> = {
  concept: '◆',
  definition: '§',
  fact: '#',
  step: '»',
  quote: '"',
  question: '?',
}

export function toMarkdown(docs: SourceDoc[], cards: Card[]): string {
  const byDoc = new Map<string, Card[]>()
  for (const c of cards) {
    if (c.status === 'hidden') continue
    const arr = byDoc.get(c.sourceId) || []
    arr.push(c)
    byDoc.set(c.sourceId, arr)
  }
  const out: string[] = ['# Synth — knowledge cards', '']
  for (const doc of docs) {
    const list = byDoc.get(doc.id)
    if (!list?.length) continue
    out.push(`## ${doc.title}`, '')
    for (const c of list) {
      out.push(`### ${TYPE_EMOJI[c.type] ?? '◆'} ${c.title}`)
      out.push('')
      if (c.summary) out.push(c.summary, '')
      for (const b of c.bullets) out.push(`- ${b}`)
      if (c.bullets.length) out.push('')
      if (c.tags.length) out.push(c.tags.map((t) => `#${t.replace(/\s+/g, '-')}`).join(' '), '')
      out.push('---', '')
    }
  }
  out.push(`> Generated by Synth · ${new Date().toISOString().slice(0, 10)}`)
  return out.join('\n')
}

function ankiField(s: string): string {
  return s.replace(/\t/g, ' ').replace(/\r?\n/g, '<br>').replace(/"/g, '""')
}

/**
 * Anki-importable TSV. Import with "Fields separated by: Tab" and
 * "Allow HTML in fields" checked.
 */
export function toAnkiTsv(cards: Card[]): string {
  const rows = ['#separator:tab', '#html:true', '#tags column:3']
  for (const c of cards) {
    if (c.status === 'hidden') continue
    const back = [c.summary, ...c.bullets.map((b) => `• ${b}`)].filter(Boolean).join('<br>')
    rows.push(
      [ankiField(c.title), ankiField(back), c.tags.map((t) => t.replace(/\s+/g, '_')).join(' ')].join(
        '\t',
      ),
    )
  }
  return rows.join('\n')
}

export function toJson(docs: SourceDoc[], cards: Card[]): string {
  return JSON.stringify({ app: 'synth', version: 2, exportedAt: Date.now(), docs, cards }, null, 2)
}

export function download(filename: string, content: string | Blob, mime = 'text/plain'): void {
  const blob = typeof content === 'string' ? new Blob([content], { type: `${mime};charset=utf-8` }) : content
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export function slugify(s: string): string {
  return (
    s
      .trim()
      .replace(/[\\/:*?"<>|]+/g, '')
      .replace(/\s+/g, '-')
      .slice(0, 48) || 'synth'
  )
}

